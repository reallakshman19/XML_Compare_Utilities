"""R4 read-only projection & hard-gated roundtrip over frozen R3 decoder.

Never derive writable CII from this projection; only baseline_r3.engine.write_cii
may serialize a byte-faithful XML tree.
"""
from __future__ import annotations
import hashlib, json, os, sys, tempfile, time
from collections import defaultdict
from decimal import Decimal
from pathlib import Path
from xml.etree import ElementTree as ET

sys.path.insert(0,str(Path(__file__).resolve().parents[1]/'baseline_r3'))
from engine import make_xml, validate, xml_bytes, load_xml, write_cii, fields, get_section, first_difference
from profile import POINTER_SECTIONS, FIELD_NAMES


def checksum(data: bytes) -> dict:
    return {'bytes':len(data),'sha256':hashlib.sha256(data).hexdigest()}


def hard_roundtrip(original:bytes) -> tuple[bytes,bytes,dict]:
    """Serialized XML is reparsed as an independent second stage. Fail closed."""
    t0=time.perf_counter()
    root=make_xml(original)
    xml=xml_bytes(root)
    t1=time.perf_counter()
    with tempfile.TemporaryDirectory(prefix='ciifr_r4_') as folder:
        x=Path(folder)/'stage.xml';x.write_bytes(xml)
        # Deliberately use XML-only writer; it cannot read original CII by path.
        regenerated=write_cii(load_xml(x))
    t2=time.perf_counter()
    verified=original==regenerated
    report={'original':checksum(original),'output':checksum(regenerated),
            'byte_differences':0 if verified else None,
            'first_difference':first_difference(original,regenerated),
            'verified':verified,'xml_bytes':len(xml),
            'parse_xml_seconds':round(t1-t0,6), 'write_seconds':round(t2-t1,6),
            'total_seconds':round(t2-t0,6)}
    if not verified:
        raise ValueError('ZERO_BYTE_GATE_FAILED: '+json.dumps(report,sort_keys=True))
    return xml,regenerated,report


def xml_only_rebuild(xml_file:Path, trusted_sha256:str, trusted_bytes:int) -> tuple[bytes,dict]:
    """Standalone XML import cannot claim original identity from XML's self-reported hash.

    Caller MUST supply a trusted expected SHA-256 and size independently obtained.
    """
    if len(trusted_sha256)!=64 or any(ch not in '0123456789abcdef' for ch in trusted_sha256.lower()):
        raise ValueError('trusted expected SHA-256 is required')
    root=load_xml(xml_file)
    if root.get('source-sha256')!=trusted_sha256.lower() or int(root.get('source-bytes'))!=trusted_bytes:
        raise ValueError('XML metadata does not match trusted expected original')
    out=write_cii(root)
    observed=checksum(out)
    if observed!={'bytes':trusted_bytes,'sha256':trusted_sha256.lower()}:
        raise ValueError('ZERO_BYTE_GATE_FAILED: regenerated bytes disagree with trusted baseline')
    return out,{'verified':True,'original':{'bytes':trusted_bytes,'sha256':trusted_sha256.lower()},
                'reconstructed':observed,'verification':'external trusted size+SHA-256'}


def snapshot(root:ET.Element) -> dict:
    """An audit-only line/element/node view. Never changes XML or emits CII."""
    def source_fields(rec):
        return [{'key':f.get('name'),'value':f.get('value'),
                 'lexeme':f.get('lexeme'),'cii_line':int(row.get('line')),
                 'kind':f.get('kind')}
                for row in rec.findall('Row') for f in row.findall('Field')]
    def number(x): return int(Decimal(x))
    els=get_section(root,'ELEMENTS').findall('Record')
    sections={p:get_section(root,p).findall('Record') for p in POINTER_SECTIONS}
    mat=get_section(root,'MISCEL_1').find('Record')
    mats=[(f,row) for row in mat.findall('Row') for f in row.findall('Field')
          if f.get('name','').startswith('material_id_')]
    if len(mats)!=len(els):raise ValueError('material assignment count mismatch')
    result={'source':{'bytes':int(root.get('source-bytes')), 'sha256':root.get('source-sha256'),
                      'profile':root.get('profile')},
            'engineering_interpretation':'SOURCE_VALUES_ONLY',
            'lines':{},'nodes':{},'pointers':[],
            'unresolved_semantics':['sentinels','material_catalog','effective_inheritance','CAESAR_validation'],
            'units':[]}
    lines=defaultdict(lambda:{'elements':[],'nodes':{}})
    nodes={}
    def get_node(num):
        return nodes.setdefault(str(num),{'number':num,'endpoints':[], 'events':[]})
    def event(n,kind,owner,pointer,ref,fields=None):
        get_node(n)['events'].append({'type':kind,'owner_element':owner,
          'section':pointer,'aux_index':ref.get('index'),'source_line':int(ref.find('Row').get('line')),
          'fields':fields or []})
    for i,rec in enumerate(els):
        fs=source_fields(rec);lookup={f['key']:f for f in fs}
        a=number(lookup['from_node']['value']); b=number(lookup['to_node']['value'])
        label=lookup['line_label']['value'].strip()  # BLANK is deliberately not inherited
        el={'element_index':i+1,'source_line':int(rec.find('Row').get('line')),
            'from':a,'to':b,'line_label':label,'material_id':number(mats[i][0].get('value')),
            'material_source_line':int(mats[i][1].get('line')),
            'properties':fs[:53], 'identity':fs[53:59],'pointers':[], 'components':[]}
        lines[label]['elements'].append(el)
        for n,side in ((a,'FROM'),(b,'TO')):
            get_node(n)['endpoints'].append({'element_index':i+1,'side':side,'line_label':label})
            lines[label]['nodes'].setdefault(str(n),set()).add(side)
        for sec in POINTER_SECTIONS:
            key='pointer_'+sec.lower().replace('&','_')
            p=number(lookup[key]['value'])
            if not p:continue
            ref=sections[sec][p-1]
            link={'element_index':i+1,'section':sec,'record_index':p,
                  'pointer_field_line':lookup[key]['cii_line'],
                  'aux_source_line':int(ref.find('Row').get('line'))}
            result['pointers'].append(link);el['pointers'].append(link)
            af=source_fields(ref); amap={f['key']:f for f in af}
            # Source-backed component evidence is ELEMENT-owned even when it
            # contains nodal association values. Never synthesize node constraints.
            el['components'].append({**link,'fields':af})
            if sec=='NODENAME':
                for role,n,keyname in [('FROM',a,'from_node_name'),('TO',b,'to_node_name')]:
                    if amap[keyname]['value'].strip():event(n,'node-name',i+1,sec,ref,[amap[keyname]])
            elif sec=='RESTRANT':
                for k in range(1,7):
                    prefix=f'dof_{k}_'; v=amap.get(prefix+'restraint_node')
                    if v and number(v['value']):
                        dest=number(v['value'])
                        dofs=[f for f in af if f['key'].startswith(prefix)]
                        event(dest,'restraint-dof',i+1,sec,ref,dofs)
                        conn=amap.get(prefix+'connecting_node')
                        if conn and number(conn['value']):event(number(conn['value']),'connecting-node',i+1,sec,ref,[conn])
            elif sec=='SIF&TEES':
                for ix in (0,42):
                    if ix<len(af) and number(af[ix]['value']):event(number(af[ix]['value']),'sif-tee',i+1,sec,ref,af[ix:ix+42])
            elif sec=='DISPLMNT':
                for ix in (0,55):
                    if ix<len(af) and number(af[ix]['value']):event(number(af[ix]['value']),'displacement',i+1,sec,ref,af[ix:ix+55])
            elif sec=='BEND':
                event(b,'bend-at-to',i+1,sec,ref,af)
                for k in (1,2,3):
                    v=amap.get(f'node_position_{k}')
                    if v and number(v['value']):event(number(v['value']),'bend-position',i+1,sec,ref,[v])
            # RIGID and REDUCERS remain attached to owning element, NEVER node.
    # Unit labels / factors are source tokens, not inferred effective units.
    units_section=get_section(root,'UNITS')
    result['units']=[{'record_index':r.get('index'),'fields':source_fields(r)}
                     for r in units_section.findall('Record')]
    for label,row in lines.items():
        owners={e['element_index'] for e in row['elements']}
        local_nodes={}
        # Endpoint entries preserve one entry per occurrence and side; never
        # reuse all events from a global node across different line owners.
        for el in row['elements']:
            for n,side in ((el['from'],'FROM'),(el['to'],'TO')):
                k=str(n)
                ent=local_nodes.setdefault(k,{'number':n,'endpoints':[], 'events':[],
                                              'auxiliary_only':True})
                ent['endpoints'].append({'element_index':el['element_index'],
                                         'side':side,'line_label':label,
                                         'source_line':el['source_line']})
                ent['auxiliary_only']=False
        # Auxiliary references can designate nodes without ELEMENT endpoints.
        # Project events by their *owner element*, not by shared node number.
        for num,all_events in nodes.items():
            owned=[e for e in all_events['events'] if e['owner_element'] in owners]
            if not owned:continue
            ent=local_nodes.setdefault(num,{'number':int(num),'endpoints':[],
                                             'events':[], 'auxiliary_only':True})
            for ix,evt in enumerate(owned):
                ent['events'].append({**evt,'event_ordinal':ix+1})
        # Keep each raw label as its JSON key. In particular the empty label
        # cannot collide with a literal engineering line named '(BLANK)'.
        result['lines'][label]={'line_label':label,'elements':row['elements'],
                     'nodes':[{'number':int(n),'roles':sorted(roles)}
                              for n,roles in sorted(row['nodes'].items(),key=lambda t:int(t[0]))],
                     'node_occurrences':[local_nodes[n] for n in sorted(local_nodes,key=int)]}
    result['nodes']=nodes
    result['counts']={'elements':len(els),'lines':len(lines), 'nodes':len(nodes),
                      'pointer_links':len(result['pointers']),
                      'blank_label_elements':len(lines.get('',{}).get('elements',[]))}
    return result

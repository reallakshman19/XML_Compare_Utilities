import {expect,test} from '@playwright/test';
import {fileURLToPath} from 'node:url';
import {readFileSync} from 'node:fs';
const original=name=>fileURLToPath(new URL('../../Benchmark/'+name+'.CII',import.meta.url));
test('canonical A2 Worker is integrated in existing Compare, preserves manual/auto lanes, never Writer',async({page})=>{
 const pageErrors=[];page.on('pageerror',e=>pageErrors.push(e.message));
 await page.goto('/tests/browser/cii-writer2-bridge-fixture.html');
 await page.evaluate(async()=>{
  localStorage.clear();
  const {installCiiWorkspaceTile}=await import('/tabs/cii-workspace/cii-workspace-tab.js');
  const host=document.createElement('section');document.body.append(host);installCiiWorkspaceTile(host);
 });
 await page.locator('[data-ciiw-open-writer2]').click();
 await page.locator('[data-ciiw-source]').setInputFiles([original('S1'),original('S2'),original('S3')]);
 await page.locator('[data-ciiw-target]').setInputFiles(original('T'));
 await page.locator('[data-ciiw-inspect]').click();
 await expect(page.locator('[data-ciiw-ms-anchor-ledger="1"]')).toBeVisible({timeout:120000});
 for(const [sid,src,tgt] of [['S2','420','415'],['S3','1580','7880']]){
  let member=page.locator('[data-ciiw-ms-member="'+sid+'"]');
  await member.locator('[data-ciiw-ms-manual-source]').fill(src);
  await member.locator('[data-ciiw-ms-manual-target]').fill(tgt);
  await member.locator('[data-ciiw-ms-manual-add]').click();
  member=page.locator('[data-ciiw-ms-member="'+sid+'"]');
  await expect(member).toContainText('ACTIVE: MANUAL');
  const selected=member.locator('[data-ciiw-evidence-card][data-selected="true"] [data-ciiw-base-action]').first();
  await selected.click();
  await expect(member).toContainText('None selected');
 }
 await page.locator('[data-ciiw-ms-compare-now]').click();
 await expect(page.locator('[data-ciiw-ms-review-table="1"]')).toBeVisible({timeout:120000});
 const compareAlternatives=page.locator('[data-ciiw-ms-reconciled-review="1"]');
 await expect(compareAlternatives).toBeVisible({timeout:180000});
 await expect(compareAlternatives).toContainText('0 independently certified and 0 Writer/Transfer operations added');
 await expect(compareAlternatives).toContainText('S2: 1→36 legacy BOUND');
 await expect(compareAlternatives).toContainText('S3: 2→34 legacy BOUND');
 await compareAlternatives.locator('details').first().locator('summary').first().click();
 const autoConflictRows=compareAlternatives.locator('tbody tr');
 await expect(autoConflictRows.filter({hasText:'S2 420'})).toContainText('MANUAL_AUTO_CONFLICT');
 await expect(autoConflictRows.filter({hasText:'S2 420'})).toContainText('10330');
 await expect(autoConflictRows.filter({hasText:'S3 1580'})).toContainText('MANUAL_AUTO_CONFLICT');
 await expect(autoConflictRows.filter({hasText:'S3 1580'})).toContainText('8895');
 await expect(page.locator('[data-ciiw-ms-apply]')).toBeDisabled();
 const panel=page.locator('[data-ciiw-f2-canonical="1"]');
 await expect(panel).toContainText('One canonical A2 solver');
 await expect(panel).toContainText('REVIEW ONLY');
 await panel.locator('[data-ciiw-f2-reconcile]').click();
 await expect(panel.locator('[data-ciiw-f2-summary]')).toBeVisible({timeout:180000});
 await expect(panel).toContainText('150 original SOURCE NODEs');
 await expect(panel).toContainText('0 certified / 0 Writer');
 const physical=page.locator('[data-ciiw-ms-reconciled-physical="1"]');
 await expect(physical).toBeVisible({timeout:30000});
 await expect(physical).toContainText('Original F2 local witness audit');
 await expect(physical).toContainText('No candidate is globally certified or Writer eligible');
 const originalChains=page.locator('[data-ciiw-f2-original-chain-review="1"]');
 await expect(originalChains).toBeVisible();
 await expect(originalChains).toContainText('98/147');
 await expect(originalChains).toContainText('49 factors lack original path evidence');
 await expect(originalChains).toContainText('0 physically certified identities');
 await originalChains.locator('details').first().locator('summary').click();
 await expect(originalChains.locator('[data-ciiw-f2-chain-group="1"]')).toHaveCount(7);
 await expect(originalChains).toContainText('Longest ordered, non-reusing original route:');
 await expect(originalChains).toContainText('global TARGET search/uniqueness NOT proved');
 await expect(page.locator('[data-ciiw-ms-apply]')).toBeDisabled();
 await expect(compareAlternatives.locator('thead')).toContainText('Original physical provenance');
 await expect(compareAlternatives.locator('tbody tr').filter({hasText:'S2 420'}))
   .toContainText('MANUAL_CONFLICT_REQUIRES_REVIEW');
 await expect(compareAlternatives.locator('tbody tr').filter({hasText:'S3 1580'}))
   .toContainText('MANUAL_CONFLICT_REQUIRES_REVIEW');

 await panel.locator('details').first().locator('summary').click();
 const conflicts=panel.locator('details').first().locator('tbody tr');
 await expect(conflicts.filter({hasText:'S2:420'})).toContainText('415');
 await expect(conflicts.filter({hasText:'S2:420'})).toContainText('10330');
 await expect(conflicts.filter({hasText:'S3:1580'})).toContainText('7880');
 await expect(conflicts.filter({hasText:'S3:1580'})).toContainText('8895');
 await expect(panel.locator('details').nth(1).locator('summary')).toContainText('39 factors');
 await panel.locator('details').nth(1).locator('summary').click();
 await expect(panel.locator('details').nth(1).locator('tbody tr')).toHaveCount(39);
 await expect(page.locator('[data-ciiw-ms-apply]')).toBeDisabled();
 const [download]=await Promise.all([page.waitForEvent('download'),panel.locator('[data-ciiw-f2-export]').click()]);
 const result=JSON.parse(readFileSync(await download.path(),'utf8'));
 expect(result.schema).toBe('CiiF2CanonicalBrowserShadow.v1');
 expect(result.summary.originalPhysicalSourceNodes).toBe(150);
 expect(result.summary.recoveredHypotheses).toBeGreaterThanOrEqual(16);
 expect(result.physicalGapLedger.schema).toBe('CiiF2PhysicalFactorGapLedger.v1');
 expect(result.physicalGapLedger.totalPhysicalSourceElements).toBe(147);
 expect(result.physicalGapLedger.originalEndpointMissingFactors).toBe(49);
 expect(result.physicalGapLedger.currentEndpointMissingFactors).toBe(33);
 expect(new Set(result.physicalGapLedger.rows.map(r=>r.sourceElementKey)).size).toBe(147);
 expect(Object.values(result.physicalGapLedger.byMember).reduce((n,x)=>n+x.physicalElementCount,0)).toBe(147);
 expect(result.physicalGapLedger.writerReady).toBe(false);
 expect(result.physicalGapLedger.writeScope).toBeNull();
 expect(result.certifiedNodeCount).toBe(0);
 expect(result.writerReady).toBe(false);
 expect(result.transferPlan).toBeNull();
 expect(result.writeScope).toBeNull();
 await page.locator('[data-ciiw-tab="inputs"]').click();
 const member=page.locator('[data-ciiw-ms-member="S2"]');
 await member.locator('[data-ciiw-evidence-card][data-selected="false"] [data-ciiw-base-action]').first().click();
 await expect(page.locator('[data-ciiw-f2-canonical="1"]')).toHaveCount(0);
 await expect(page.locator('[data-ciiw-f2-original-chain-review="1"]')).toHaveCount(0);
 expect(pageErrors.filter(x=>/cii-workspace-f2|A2_|SHA256/i.test(x))).toEqual([]);
});

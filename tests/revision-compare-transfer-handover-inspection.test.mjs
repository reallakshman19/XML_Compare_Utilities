import assert from 'node:assert/strict';
import { serializeRevisionCompareTransferHandoverBundle } from '../tabs/revision-compare/revision-transfer-handover.js';
import { verifyRevisionCompareTransferHandoverText } from '../tabs/revision-compare/revision-transfer-handover-inspection.js';
import { createRevisionCompareHandoverInspectionState, startRevisionCompareHandoverInspection, completeRevisionCompareHandoverInspection, failRevisionCompareHandoverInspection, clearRevisionCompareHandoverInspection } from '../tabs/revision-compare/revision-transfer-handover-inspection-state.js';
import { adoptRevisionCompareHandoverInspectionWorkspace, revisionCompareWorkspaceIsFreshForHandoverInspection } from '../tabs/revision-compare/revision-transfer-handover-inspection-workspace-state.js';
import { clone, cryptoRef, transferArchiveFixture } from './revision-compare-transfer-archive-fixtures.mjs';

const fixture = await transferArchiveFixture();
const bundle = fixture.workspace.transferCompletion.bundle;
const text = serializeRevisionCompareTransferHandoverBundle(bundle);
const verified = await verifyRevisionCompareTransferHandoverText(text, { cryptoRef });
assert.equal(verified.bundleId, bundle.bundleId);
assert.equal(Object.isFrozen(verified), true);
await assert.rejects(() => verifyRevisionCompareTransferHandoverText(` ${text}`, { cryptoRef }), /canonical serialization/);
await assert.rejects(() => verifyRevisionCompareTransferHandoverText(`\uFEFF${text}`, { cryptoRef }), /byte-order mark/);
const broken = clone(bundle); broken.payload.transferArtifacts[0].text += ' ';
await assert.rejects(() => verifyRevisionCompareTransferHandoverText(serializeRevisionCompareTransferHandoverBundle(broken), { cryptoRef }), /artifact SHA-256/);
const initial = createRevisionCompareHandoverInspectionState();
const importing = startRevisionCompareHandoverInspection(initial, { name: 'handover.json', size: text.length });
const complete = completeRevisionCompareHandoverInspection(importing, importing.requestGeneration, verified);
assert.equal(complete.status, 'VERIFIED');
assert.equal(complete.bundleId, bundle.bundleId);
assert.equal(completeRevisionCompareHandoverInspection(importing, importing.requestGeneration - 1, verified), importing);
const failed = failRevisionCompareHandoverInspection(importing, importing.requestGeneration, new Error('broken'));
assert.equal(failed.status, 'FAILED'); assert.equal(failed.bundle, null);
assert.equal(clearRevisionCompareHandoverInspection(complete).status, 'IDLE');
const fresh = adoptRevisionCompareHandoverInspectionWorkspace(fixture.workspace);
assert.equal(fresh.schema, 'RevisionCompareWorkspaceState.v14');
assert.equal(revisionCompareWorkspaceIsFreshForHandoverInspection(fresh), false);
const blank = adoptRevisionCompareHandoverInspectionWorkspace({ schema: 'RevisionCompareWorkspaceState.v13', slots: { baseline: {}, candidate: {} }, session: { documents: {} }, compare: {}, review: {}, decision: {}, transfer: {}, transferCompletion: {}, transferArchive: {} });
assert.equal(revisionCompareWorkspaceIsFreshForHandoverInspection(blank), true);
console.log('revision-compare-transfer-handover-inspection.test.mjs passed');

import assert from 'node:assert/strict';
import { buildCiiComparisonPathProjection } from '../tabs/cii-workspace/cii-workspace-path-normalization.js';
import { validateCiiPathTotalLengthToleranceMm,evaluateCiiPathTotalLength } from '../tabs/cii-workspace/cii-workspace-path-total-length.js';
const pipe=(id,from,to,len,extra={})=>({elementId:id,from:String(from),to:String(to),dx:len,dy:0,dz:0,lengthMm:len,
  componentKind:'PIPE',diameter:150,wall:8,packetEvidence:[],isAnchorElement:false,...extra});
const graph=(...edges)=>({edges});
const source=graph(pipe('S-1',10,20,2000),pipe('S-2',20,30,2000));
const target=graph(pipe('T-1',5010,5015,4050));
const verified={20:{state:'VERIFIED_EMPTY',complete:true}};
const original=JSON.stringify(source);
const normalized=buildCiiComparisonPathProjection(source,{attachmentEvidenceByNode:verified});
assert.equal(normalized.comparisonPathCount,1);
const terminalMarked=graph(pipe('E-1',10,20,2000,{isAnchorElement:true}),pipe('E-2',20,30,2000,{isAnchorElement:true}));
assert.equal(buildCiiComparisonPathProjection(terminalMarked,{attachmentEvidenceByNode:verified}).comparisonPathCount,1,'terminal flags on remote ends must not block interior plain node');
assert.deepEqual(normalized.paths[0].originalNodeIds,['10','20','30']);
assert.deepEqual(normalized.paths[0].interiorPassThroughNodeIds,['20']);
assert.deepEqual(normalized.paths[0].originalElementIds,['S-1','S-2']);
assert.equal(normalized.paths[0].totalLengthMm,4000);
assert.equal(JSON.stringify(source),original);
const t=buildCiiComparisonPathProjection(target);
assert.equal(t.paths[0].totalLengthMm,4050);
const proof=evaluateCiiPathTotalLength(normalized.paths[0],t.paths[0]);
assert.equal(proof.lengthPass,true);
assert.equal(proof.deltaMm,50);
assert.equal(proof.identityCertified,false);
assert.equal(proof.writerAuthorized,false);
assert.equal(normalized.methodBAxesInferred,0);
assert.equal(buildCiiComparisonPathProjection(source).comparisonPathCount,2,'no proof of absent attachments means no collapse');
assert.equal(buildCiiComparisonPathProjection(source,{attachmentEvidenceByNode:{20:{state:'ATTACHED',complete:true}}}).comparisonPathCount,2);
assert.equal(buildCiiComparisonPathProjection(source,{attachmentEvidenceByNode:verified,protectedNodeIds:['20']}).comparisonPathCount,2);
assert.equal(buildCiiComparisonPathProjection(graph(pipe('S-1',10,20,2000),pipe('S-2',20,30,2000,{wall:9})),{attachmentEvidenceByNode:verified}).comparisonPathCount,2);
const bent=graph(pipe('B-1',10,20,2000),pipe('B-2',20,30,2000,{dx:0,dy:2000}));
assert.equal(buildCiiComparisonPathProjection(bent,{attachmentEvidenceByNode:verified}).comparisonPathCount,2);
const branched=graph(...source.edges,pipe('S-3',20,40,1000));
assert.equal(buildCiiComparisonPathProjection(branched,{attachmentEvidenceByNode:verified}).comparisonPathCount,3);
assert.equal(evaluateCiiPathTotalLength({totalLengthMm:4000},{totalLengthMm:4100}).lengthPass,true);
assert.equal(evaluateCiiPathTotalLength({totalLengthMm:4000},{totalLengthMm:4101}).lengthPass,false);
assert.equal(evaluateCiiPathTotalLength({totalLengthMm:4000},{totalLengthMm:4000}).identityCertified,false);
for(const invalid of [null,'',-1,NaN,Infinity,1001])assert.throws(()=>validateCiiPathTotalLengthToleranceMm(invalid),/TOLERANCE_INVALID/);
assert.equal(validateCiiPathTotalLengthToleranceMm(100),100);
console.log('PASS CII Phase2 read-only safe normalization and cumulative 100mm evidence; zero Method A/B/Writer qualification');
